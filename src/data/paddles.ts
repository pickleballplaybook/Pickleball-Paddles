// ── Utility exports ────────────────────────────────────────────────────────────

export const brands     = Array.from(new Set(paddles.map((p) => p.brand))).sort();
export const shapes     = Array.from(new Set(paddles.map((p) => p.shape))).sort();
export const thicknesses = Array.from(new Set(paddles.map((p) => p.thickness)))
  .sort((a, b) => parseFloat(a) - parseFloat(b));

export function getPaddleBySlug(slug: string): Paddle | undefined {
  return paddles.find((p) => p.slug === slug);
}

export function getFilteredPaddles(brand: string, shape: string): Paddle[] {
  return paddles.filter((p) => {
    if (brand && brand !== "All" && p.brand !== brand) return false;
    if (shape && shape !== "All" && p.shape !== shape) return false;
    return true;
  });
}

export function getJustAdded(count: number): Paddle[] {
  return [...paddles]
    .sort((a, b) => new Date(b.addedAt).getTime() - new Date(a.addedAt).getTime())
    .slice(0, count);
}

export function getLatestPaddles(count: number): Paddle[] {
  return [...paddles]
    .sort((a, b) => {
      const dateDiff = new Date(b.addedAt).getTime() - new Date(a.addedAt).getTime();
      if (dateDiff !== 0) return dateDiff;
      return b.trendingScore - a.trendingScore; // higher trendingScore = higher priority
    })
    .slice(0, count);
}

export function getTrending(count: number): Paddle[] {
  return [...paddles]
    .sort((a, b) => b.trendingScore - a.trendingScore)
    .slice(0, count);
}
